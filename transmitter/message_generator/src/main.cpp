// ── Helper: send an array of CANMessages ──────────────────────────────────────
void sendMessages(const CANMessage* msgs, size_t count, uint16_t intervalMs = 10) {
  can_frame frame;
  frame.can_dlc = 8;

  for (size_t i = 0; i < count; i++) {
    frame.can_id = msgs[i].id;
    memcpy(frame.data, msgs[i].data, 8);

    MCP2515::ERROR err = mcp2515.sendMessage(&frame);

    Serial.print(err == MCP2515::ERROR_OK ? "[OK]  " : "[ERR] ");
    Serial.print("ID: 0x");
    Serial.print(msgs[i].id, HEX);
    Serial.print("  Data:");
    for (int b = 0; b < 8; b++) {
      Serial.print(" ");
      if (msgs[i].data[b] < 0x10) Serial.print("0");
      Serial.print(msgs[i].data[b], HEX);
    }
    Serial.println();

    delay(intervalMs);
  }
}

// ── Setup ─────────────────────────────────────────────────────────────────────
void setup() {
  Serial.begin(115200);
  while (!Serial);
  Serial.println("Booting...");

  SPI.begin();
  mcp2515.reset();
  mcp2515.setBitrate(CAN_500KBPS, MCP_8MHZ); // Change to MCP_16MHZ if needed
  mcp2515.setNormalMode();

  Serial.println("MCP2515 ready.\n");
}

// ── Loop ──────────────────────────────────────────────────────────────────────
